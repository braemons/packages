#!/bin/bash
# Reindex one suite of the archive, optionally adding packages to it first.
#
#   bin/build-repo.sh <archive-dir> <suite> [deb-dir]
#
# The output is a plain static tree — no server-side software — so it serves
# identically from GitHub Pages, an nginx docroot, or an rsync'd copy on a lab
# server for machines with no internet access.
#
# Environment:
#   ORIGIN / LABEL   Release file metadata (default: braemons / braemons)
#   ARCHES           architectures to index (default: amd64 arm64)
#   APT_SIGNING_KEY  ASCII-armored private key. Unset produces an UNSIGNED
#                    suite, which apt only accepts with [trusted=yes].
set -euo pipefail

ARCHIVE=${1:?usage: build-repo.sh <archive-dir> <suite> [deb-dir]}
SUITE=${2:?usage: build-repo.sh <archive-dir> <suite> [deb-dir]}
DEB_DIR=${3:-}

ORIGIN=${ORIGIN:-braemons}
LABEL=${LABEL:-braemons}
ARCHES=${ARCHES:-amd64 arm64}

# pool/<suite>/main/<first-letter>/<package>/<file>.deb.
#
# Debian shares one pool across suites, but the index is generated by scanning
# a directory: a shared pool would put every pre-release into the 'stable'
# Packages file, which is the opposite of why the suites are split.
POOL="pool/$SUITE/main"

# ── Add packages ──────────────────────────────────────────────────────────────
if [ -n "$DEB_DIR" ]; then
    shopt -s nullglob
    debs=("$DEB_DIR"/*.deb)
    [ ${#debs[@]} -gt 0 ] || { echo "build-repo.sh: no .deb files in $DEB_DIR" >&2; exit 1; }

    for deb in "${debs[@]}"; do
        pkg=$(dpkg-deb -f "$deb" Package)
        dest="$ARCHIVE/$POOL/${pkg:0:1}/$pkg"
        mkdir -p "$dest"
        cp -f "$deb" "$dest/"
        echo "    + $POOL/${pkg:0:1}/$pkg/$(basename "$deb")"
    done
fi

[ -d "$ARCHIVE/$POOL" ] || { echo "build-repo.sh: suite '$SUITE' has no pool" >&2; exit 1; }

# ── Per-architecture indices ─────────────────────────────────────────────────
for arch in $ARCHES; do
    dir="$ARCHIVE/dists/$SUITE/main/binary-$arch"
    mkdir -p "$dir"
    # Filename: is resolved relative to the archive root, so scan from there.
    ( cd "$ARCHIVE" && apt-ftparchive --arch "$arch" packages "$POOL" ) > "$dir/Packages"
    gzip -9kf "$dir/Packages"
    echo "    $SUITE/$arch: $(grep -c '^Package: ' "$dir/Packages" || true) package(s)"
    # An architecture with no packages still needs an (empty) index published:
    # apt fails the whole suite if a declared architecture is missing one.
done

# ── Release ───────────────────────────────────────────────────────────────────
conf=$(mktemp)
cat > "$conf" <<EOF
APT::FTPArchive::Release::Origin "$ORIGIN";
APT::FTPArchive::Release::Label "$LABEL";
APT::FTPArchive::Release::Suite "$SUITE";
APT::FTPArchive::Release::Codename "$SUITE";
APT::FTPArchive::Release::Architectures "$ARCHES";
APT::FTPArchive::Release::Components "main";
APT::FTPArchive::Release::Description "braemons packages ($SUITE)";
EOF
( cd "$ARCHIVE" && apt-ftparchive -c "$conf" release "dists/$SUITE" ) \
    > "$ARCHIVE/dists/$SUITE/Release"
rm -f "$conf"

# ── Signature ─────────────────────────────────────────────────────────────────
if [ -n "${APT_SIGNING_KEY:-}" ]; then
    GNUPGHOME=$(mktemp -d); export GNUPGHOME
    chmod 700 "$GNUPGHOME"
    printf '%s' "$APT_SIGNING_KEY" | gpg --batch --quiet --import

    keyid=$(gpg --batch --with-colons --list-secret-keys | awk -F: '/^sec:/ {print $5; exit}')
    [ -n "$keyid" ] || { echo "build-repo.sh: no secret key in APT_SIGNING_KEY" >&2; exit 1; }

    rel="$ARCHIVE/dists/$SUITE/Release"
    # InRelease is what modern apt fetches; Release.gpg keeps older clients and
    # mirroring tools working.
    gpg --batch --yes --local-user "$keyid" --armor --detach-sign --output "$rel.gpg" "$rel"
    gpg --batch --yes --local-user "$keyid" --clearsign --output "$ARCHIVE/dists/$SUITE/InRelease" "$rel"

    rm -rf "$GNUPGHOME"
    echo "    signed $SUITE with $keyid"
else
    echo "WARNING: APT_SIGNING_KEY unset — suite '$SUITE' is UNSIGNED." >&2
fi
